CREATE TABLE IF NOT EXISTS DP_BASE_GOLD.DEPARTMENT_PERFORMANCE(
  DEPT_ID STRING
  OPTIONS (description = 'UNIQUE IDENTIFIER FOR THE DEPARTMENT'),
  DEPARTMENTNAME STRING
  OPTIONS (description = 'NAME OF THE CLINICAL DEPARTMENT'),
  TOTALENCOUNTERS INT64
  OPTIONS (description = 'TOTAL NUMBER OF ENCOUNTERS WITHIN THE DEPARTMENT'),
  TOTALTRANSACTIONS INT64
  OPTIONS (description = 'TOTAL NUMBER OF TRANSACTIONS WITHIN THE DEPARTMENT'),
  TOTALBILLEDAMOUNT FLOAT64
  OPTIONS (description = 'TOTAL AMOUNT BILLED BY THE DEPARTMENT'),
  TOTALPAIDAMOUNT FLOAT64
  OPTIONS (description = 'TOTAL AMOUNT PAID TO THE DEPARTMENT'),
  AVGPAYMENTPERTRANSACTION FLOAT64
  OPTIONS (description = 'AVERAGE PAYMENT RECEIVED PER INDIVIDUAL TRANSACTION'))
  OPTIONS (
    description = 'GOLD LAYER TABLE ANALYZING DEPARTMENT-LEVEL FINANCIAL AND OPERATIONAL PERFORMANCE');