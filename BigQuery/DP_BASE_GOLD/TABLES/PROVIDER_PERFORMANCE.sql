CREATE TABLE IF NOT EXISTS DP_BASE_GOLD.PROVIDER_PERFORMANCE(
  PROVIDERID STRING
  OPTIONS (description = 'UNIQUE IDENTIFIER FOR THE PROVIDER'), FIRSTNAME STRING
  OPTIONS (description = 'PROVIDER FIRST NAME'), LASTNAME STRING
  OPTIONS (description = 'PROVIDER LAST NAME'), SPECIALIZATION STRING
  OPTIONS (description = 'MEDICAL SPECIALTY OF THE PROVIDER'),
  TOTALENCOUNTERS INT64
  OPTIONS (description = 'TOTAL NUMBER OF PATIENT ENCOUNTERS HANDLED'),
  TOTALTRANSACTIONS INT64
  OPTIONS (description = 'TOTAL NUMBER OF BILLING TRANSACTIONS PROCESSED'),
  TOTALBILLEDAMOUNT FLOAT64
  OPTIONS (description = 'CUMULATIVE AMOUNT BILLED BY THE PROVIDER'),
  TOTALPAIDAMOUNT FLOAT64
  OPTIONS (description = 'CUMULATIVE AMOUNT PAID TO THE PROVIDER'),
  APPROVEDCLAIMS INT64
  OPTIONS (description = 'TOTAL NUMBER OF APPROVED INSURANCE CLAIMS'),
  TOTALCLAIMS INT64
  OPTIONS (description = 'TOTAL NUMBER OF CLAIMS SUBMITTED'),
  CLAIMAPPROVALRATE FLOAT64
  OPTIONS (description = 'PERCENTAGE OF CLAIMS THAT WERE APPROVED'))
  OPTIONS (
    description = 'GOLD LAYER TABLE ANALYZING INDIVIDUAL PROVIDER PRODUCTIVITY AND CLAIM PERFORMANCE');
