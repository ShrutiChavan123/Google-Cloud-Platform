CREATE TABLE IF NOT EXISTS DP_BASE_GOLD.PATIENT_HISTORY(
  PATIENT_KEY STRING
  OPTIONS (description = 'UNIQUE KEY IDENTIFYING THE PATIENT'), FIRSTNAME STRING
  OPTIONS (description = 'PATIENT FIRST NAME'), LASTNAME STRING
  OPTIONS (description = 'PATIENT LAST NAME'), GENDER STRING
  OPTIONS (description = 'PATIENT GENDER'), DOB INT64
  OPTIONS (description = 'DATE OF BIRTH IN YYYYMMDD FORMAT'), ADDRESS STRING
  OPTIONS (description = 'PATIENT RESIDENTIAL ADDRESS'), ENCOUNTERDATE INT64
  OPTIONS (description = 'DATE OF THE PATIENT ENCOUNTER'), ENCOUNTERTYPE STRING
  OPTIONS (description = 'TYPE OF ENCOUNTER E.G. INPATIENT, OUTPATIENT'),
  TRANSACTION_KEY STRING
  OPTIONS (description = 'UNIQUE KEY IDENTIFYING THE BILLING TRANSACTION'),
  VISITDATE INT64
  OPTIONS (description = 'DATE OF THE ACTUAL CLINICAL VISIT'), SERVICEDATE INT64
  OPTIONS (description = 'DATE THE MEDICAL SERVICE WAS RENDERED'),
  BILLEDAMOUNT FLOAT64
  OPTIONS (description = 'TOTAL AMOUNT BILLED FOR THE SERVICE'),
  PAIDAMOUNT FLOAT64
  OPTIONS (description = 'TOTAL AMOUNT PAID BY THE PATIENT OR PAYOR'),
  CLAIMSTATUS STRING
  OPTIONS (description = 'CURRENT STATUS OF THE INSURANCE CLAIM'),
  CLAIMAMOUNT STRING
  OPTIONS (description = 'TOTAL AMOUNT SUBMITTED IN THE CLAIM'),
  CLAIMPAIDAMOUNT STRING
  OPTIONS (description = 'AMOUNT PAID BY THE INSURANCE FOR THE CLAIM'),
  PAYORTYPE STRING
  OPTIONS (description = 'TYPE OF PAYOR E.G. PRIVATE, MEDICARE'))
  OPTIONS (
    description = 'COMPREHENSIVE TABLE TRACKING HISTORICAL PATIENT ENCOUNTERS AND BILLING DATA');