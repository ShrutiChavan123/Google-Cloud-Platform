CREATE OR REPLACE PROCEDURE `dp-dwh-dev.DP_BASE_GOLD.SP_LOAD_PROVIDER_CHARGE_SUMMARY`()
BEGIN TRUNCATE TABLE `DP_BASE_GOLD.PROVIDER_CHARGE_SUMMARY`;

# INSERT DATA
INSERT INTO `DP_BASE_GOLD.PROVIDER_CHARGE_SUMMARY`
SELECT
  CONCAT(P.FIRSTNAME, ' ', P.LASTNAME) AS PROVIDER_NAME,
  D.NAME AS DEPT_NAME,
  SUM(T.AMOUNT) AS AMOUNT
FROM `DP_BASE_SILVER.TRANSACTIONS` T
LEFT JOIN `DP_BASE_SILVER.PROVIDERS` P
  ON SPLIT(P.PROVIDERID, "-")[SAFE_OFFSET(1)] = T.PROVIDERID
LEFT JOIN `DP_BASE_SILVER.DEPARTMENTS` D
  ON SPLIT(D.DEPARTMENT_ID, "-")[SAFE_OFFSET(0)] = P.DEPTID
WHERE T.IS_QUARANTINED = FALSE AND D.NAME IS NOT NULL
GROUP BY PROVIDER_NAME, DEPT_NAME;

END;