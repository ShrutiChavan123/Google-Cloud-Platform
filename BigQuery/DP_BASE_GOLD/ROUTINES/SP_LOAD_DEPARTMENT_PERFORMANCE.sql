CREATE OR REPLACE PROCEDURE `dp-dwh-dev.DP_BASE_GOLD.SP_LOAD_DEPARTMENT_PERFORMANCE`()
BEGIN

        -- TRUNCATE TABLE
        TRUNCATE TABLE `DP_BASE_GOLD.DEPARTMENT_PERFORMANCE`;

-- INSERT DATA
INSERT INTO `DP_BASE_GOLD.DEPARTMENT_PERFORMANCE`
SELECT
  D.DEPARTMENT_ID,
  D.NAME AS DEPARTMENTNAME,
  COUNT(DISTINCT E.ENCOUNTER_KEY) AS TOTALENCOUNTERS,
  COUNT(DISTINCT T.TRANSACTION_KEY) AS TOTALTRANSACTIONS,
  SUM(T.AMOUNT) AS TOTALBILLEDAMOUNT,
  SUM(T.PAIDAMOUNT) AS TOTALPAIDAMOUNT,
  AVG(T.PAIDAMOUNT) AS AVGPAYMENTPERTRANSACTION
FROM `DP_BASE_SILVER.DEPARTMENTS` D
LEFT JOIN `DP_BASE_SILVER.ENCOUNTERS` E
  ON SPLIT(D.DEPARTMENT_ID, "-")[SAFE_OFFSET(0)] = E.DEPARTMENTID
LEFT JOIN `DP_BASE_SILVER.TRANSACTIONS` T
  ON SPLIT(D.DEPARTMENT_ID, "-")[SAFE_OFFSET(0)] = T.DEPTID
WHERE D.IS_QUARANTINE = FALSE
GROUP BY D.DEPARTMENT_ID, D.NAME;

END;