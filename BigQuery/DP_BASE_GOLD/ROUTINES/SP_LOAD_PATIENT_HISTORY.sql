CREATE OR REPLACE PROCEDURE `dp-dwh-dev.DP_BASE_GOLD.SP_LOAD_PATIENT_HISTORY`()
BEGIN

        -- TRUNCATE TABLE
        TRUNCATE TABLE `DP_BASE_GOLD.PATIENT_HISTORY`;

-- INSERT DATA
INSERT INTO `DP_BASE_GOLD.PATIENT_HISTORY`
SELECT
  P.PATIENT_KEY,
  P.FIRSTNAME,
  P.LASTNAME,
  P.GENDER,
  P.DOB,
  P.ADDRESS,
  E.ENCOUNTERDATE,
  E.ENCOUNTERTYPE,
  T.TRANSACTION_KEY,
  T.VISITDATE,
  T.SERVICEDATE,
  T.AMOUNT AS BILLEDAMOUNT,
  T.PAIDAMOUNT,
  C.CLAIMSTATUS,
  C.CLAIMAMOUNT,
  C.PAIDAMOUNT AS CLAIMPAIDAMOUNT,
  C.PAYORTYPE
FROM `DP_BASE_SILVER.PATIENTS` P
LEFT JOIN `DP_BASE_SILVER.ENCOUNTERS` E
  ON
    SPLIT(P.PATIENT_KEY, '-')[OFFSET(0)]
      || '-'
      || SPLIT(P.PATIENT_KEY, '-')[OFFSET(1)]
    = E.PATIENTID
LEFT JOIN `DP_BASE_SILVER.TRANSACTIONS` T
  ON
    SPLIT(P.PATIENT_KEY, '-')[OFFSET(0)]
      || '-'
      || SPLIT(P.PATIENT_KEY, '-')[OFFSET(1)]
    = T.PATIENTID
LEFT JOIN `DP_BASE_SILVER.CLAIMS` C
  ON T.SRC_TRANSACTIONID = C.TRANSACTIONID
WHERE P.IS_CURRENT = TRUE;

END;