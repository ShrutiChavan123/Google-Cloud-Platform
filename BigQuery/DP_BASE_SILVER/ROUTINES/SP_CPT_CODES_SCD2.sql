CREATE OR REPLACE PROCEDURE `dp-dwh-dev.DP_BASE_SILVER.SP_CPT_CODES_SCD2`()
BEGIN
-- 1. Create a staging table from Bronze source with Uppercase Columns and Quality Logic
CREATE OR REPLACE TABLE `dp-dwh-dev.DP_BASE_TEMP.TEMP_CPT_CODES`
AS
SELECT
  CONCAT(CPT_CODES, '-', DATASOURCE) AS CP_CODE_KEY,
  PROCEDURE_CODE_CATEGORY,
  CPT_CODES,
  PROCEDURE_CODE_DESCRIPTIONS,
  CODE_STATUS,
  DATASOURCE,
  CASE
    WHEN CPT_CODES IS NULL OR LOWER(CODE_STATUS) = 'null' THEN TRUE
    ELSE FALSE
    END
    AS IS_QUARANTINED
FROM
  (
    SELECT
      procedure_code_category AS PROCEDURE_CODE_CATEGORY,
      cpt_codes AS CPT_CODES,
      procedure_code_descriptions AS PROCEDURE_CODE_DESCRIPTIONS,
      code_status AS CODE_STATUS,
      'hosa' AS DATASOURCE
    FROM `dp-dwh-dev.DP_BASE_BRONZE.CPT_CODES`
  );

-- 2. SCD Type 2 Part A: Expire (deactivate) existing records in Silver that have changed
MERGE INTO `dp-dwh-dev.DP_BASE_SILVER.CPT_CODES` AS TGT
USING `dp-dwh-dev.DP_BASE_TEMP.TEMP_CPT_CODES` AS SRC
ON
  TGT.CP_CODE_KEY = SRC.CP_CODE_KEY
  AND TGT.IS_CURRENT
    = TRUE
      WHEN
        MATCHED
        AND (
          TGT.PROCEDURE_CODE_CATEGORY <> SRC.PROCEDURE_CODE_CATEGORY
          OR TGT.CPT_CODES <> SRC.CPT_CODES
          OR TGT.PROCEDURE_CODE_DESCRIPTIONS <> SRC.PROCEDURE_CODE_DESCRIPTIONS
          OR TGT.CODE_STATUS <> SRC.CODE_STATUS
          OR TGT.DATASOURCE <> SRC.DATASOURCE
          OR TGT.IS_QUARANTINED <> SRC.IS_QUARANTINED)
        THEN UPDATE
SET TGT.IS_CURRENT = FALSE, TGT.MODIFIED_DATE = CURRENT_TIMESTAMP();

-- 3. SCD Type 2 Part B: Insert new records and the new versions of updated records
INSERT INTO `dp-dwh-dev.DP_BASE_SILVER.CPT_CODES`
  (
    CP_CODE_KEY,
    PROCEDURE_CODE_CATEGORY,
    CPT_CODES,
    PROCEDURE_CODE_DESCRIPTIONS,
    CODE_STATUS,
    DATASOURCE,
    IS_QUARANTINED,
    INSERTED_DATE,
    MODIFIED_DATE,
    IS_CURRENT)
SELECT
  SRC.CP_CODE_KEY,
  SRC.PROCEDURE_CODE_CATEGORY,
  SRC.CPT_CODES,
  SRC.PROCEDURE_CODE_DESCRIPTIONS,
  SRC.CODE_STATUS,
  SRC.DATASOURCE,
  SRC.IS_QUARANTINED,
  CURRENT_TIMESTAMP(),
  CURRENT_TIMESTAMP(),
  TRUE
FROM `dp-dwh-dev.DP_BASE_TEMP.TEMP_CPT_CODES` AS SRC
WHERE
  NOT EXISTS(
    SELECT 1
    FROM `dp-dwh-dev.DP_BASE_SILVER.CPT_CODES` AS TGT
    WHERE TGT.CP_CODE_KEY = SRC.CP_CODE_KEY AND TGT.IS_CURRENT = TRUE
  );

-- 4. Cleanup the temporary staging table
DROP TABLE IF EXISTS `dp-dwh-dev.DP_BASE_TEMP.TEMP_CPT_CODES`;

END;