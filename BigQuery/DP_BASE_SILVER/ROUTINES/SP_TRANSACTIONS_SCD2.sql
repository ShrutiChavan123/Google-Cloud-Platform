CREATE OR REPLACE PROCEDURE `dp-dwh-dev.DP_BASE_SILVER.SP_TRANSACTIONS_SCD2`()
BEGIN
-- 1. Create a staging table from Bronze sources with Uppercase Columns and Quality Logic
CREATE OR REPLACE TABLE `dp-dwh-dev.DP_BASE_TEMP.TEMP_TRANSACTIONS`
AS
SELECT DISTINCT
  CONCAT(SRC_TRANSACTIONID, '-', DATASOURCE) AS TRANSACTION_KEY,
  SRC_TRANSACTIONID,
  ENCOUNTERID,
  PATIENTID,
  PROVIDERID,
  DEPTID,
  VISITDATE,
  SERVICEDATE,
  PAIDDATE,
  VISITTYPE,
  AMOUNT,
  AMOUNTTYPE,
  PAIDAMOUNT,
  CLAIMID,
  PAYORID,
  PROCEDURECODE,
  ICDCODE,
  LINEOFBUSINESS,
  MEDICAIDID,
  MEDICAREID,
  SRC_INSERTDATE,
  SRC_MODIFIEDDATE,
  DATASOURCE,
  CASE
    WHEN
      ENCOUNTERID IS NULL
      OR PATIENTID IS NULL
      OR SRC_TRANSACTIONID IS NULL
      OR VISITDATE IS NULL
      THEN TRUE
    ELSE FALSE
    END
    AS IS_QUARANTINED
FROM
  (
    SELECT DISTINCT
      TransactionID AS SRC_TRANSACTIONID,
      EncounterID AS ENCOUNTERID,
      PatientID AS PATIENTID,
      ProviderID AS PROVIDERID,
      DeptID AS DEPTID,
      VisitDate AS VISITDATE,
      ServiceDate AS SERVICEDATE,
      PaidDate AS PAIDDATE,
      VisitType AS VISITTYPE,
      Amount AS AMOUNT,
      AmountType AS AMOUNTTYPE,
      PaidAmount AS PAIDAMOUNT,
      ClaimID AS CLAIMID,
      PayorID AS PAYORID,
      ProcedureCode AS PROCEDURECODE,
      ICDCode AS ICDCODE,
      LineOfBusiness AS LINEOFBUSINESS,
      MedicaidID AS MEDICAIDID,
      MedicareID AS MEDICAREID,
      InsertDate AS SRC_INSERTDATE,
      ModifiedDate AS SRC_MODIFIEDDATE,
      'hosa' AS DATASOURCE
    FROM `dp-dwh-dev.DP_BASE_BRONZE.TRANSACTIONS_HA`
    UNION ALL
    SELECT DISTINCT
      TransactionID AS SRC_TRANSACTIONID,
      EncounterID AS ENCOUNTERID,
      PatientID AS PATIENTID,
      ProviderID AS PROVIDERID,
      DeptID AS DEPTID,
      VisitDate AS VISITDATE,
      ServiceDate AS SERVICEDATE,
      PaidDate AS PAIDDATE,
      VisitType AS VISITTYPE,
      Amount AS AMOUNT,
      AmountType AS AMOUNTTYPE,
      PaidAmount AS PAIDAMOUNT,
      ClaimID AS CLAIMID,
      PayorID AS PAYORID,
      ProcedureCode AS PROCEDURECODE,
      ICDCode AS ICDCODE,
      LineOfBusiness AS LINEOFBUSINESS,
      MedicaidID AS MEDICAIDID,
      MedicareID AS MEDICAREID,
      InsertDate AS SRC_INSERTDATE,
      ModifiedDate AS SRC_MODIFIEDDATE,
      'hosb' AS DATASOURCE
    FROM `dp-dwh-dev.DP_BASE_BRONZE.TRANSACTIONS_HB`
  );

-- 2. SCD Type 2 Part A: Expire (deactivate) existing records in Silver that have changed
MERGE INTO `dp-dwh-dev.DP_BASE_SILVER.TRANSACTIONS` AS TGT
USING `dp-dwh-dev.DP_BASE_TEMP.TEMP_TRANSACTIONS` AS SRC
ON
  TGT.TRANSACTION_KEY = SRC.TRANSACTION_KEY
  AND TGT.IS_CURRENT
    = TRUE
      WHEN
        MATCHED
        AND (
          TGT.SRC_TRANSACTIONID <> SRC.SRC_TRANSACTIONID
          OR TGT.ENCOUNTERID <> SRC.ENCOUNTERID
          OR TGT.PATIENTID <> SRC.PATIENTID
          OR TGT.PROVIDERID <> SRC.PROVIDERID
          OR TGT.DEPTID <> SRC.DEPTID
          OR TGT.VISITDATE <> SRC.VISITDATE
          OR TGT.SERVICEDATE <> SRC.SERVICEDATE
          OR TGT.PAIDDATE <> SRC.PAIDDATE
          OR TGT.VISITTYPE <> SRC.VISITTYPE
          OR TGT.AMOUNT <> SRC.AMOUNT
          OR TGT.AMOUNTTYPE <> SRC.AMOUNTTYPE
          OR TGT.PAIDAMOUNT <> SRC.PAIDAMOUNT
          OR TGT.CLAIMID <> SRC.CLAIMID
          OR TGT.PAYORID <> SRC.PAYORID
          OR TGT.PROCEDURECODE <> SRC.PROCEDURECODE
          OR TGT.ICDCODE <> SRC.ICDCODE
          OR TGT.LINEOFBUSINESS <> SRC.LINEOFBUSINESS
          OR TGT.MEDICAIDID <> SRC.MEDICAIDID
          OR TGT.MEDICAREID <> SRC.MEDICAREID
          OR TGT.SRC_INSERTDATE <> SRC.SRC_INSERTDATE
          OR TGT.SRC_MODIFIEDDATE <> SRC.SRC_MODIFIEDDATE
          OR TGT.DATASOURCE <> SRC.DATASOURCE
          OR TGT.IS_QUARANTINED <> SRC.IS_QUARANTINED)
        THEN UPDATE
SET TGT.IS_CURRENT = FALSE, TGT.MODIFIED_DATE = CURRENT_TIMESTAMP();

-- 3. SCD Type 2 Part B: Insert new records and the new versions of updated records
INSERT INTO `dp-dwh-dev.DP_BASE_SILVER.TRANSACTIONS`
  (
    TRANSACTION_KEY,
    SRC_TRANSACTIONID,
    ENCOUNTERID,
    PATIENTID,
    PROVIDERID,
    DEPTID,
    VISITDATE,
    SERVICEDATE,
    PAIDDATE,
    VISITTYPE,
    AMOUNT,
    AMOUNTTYPE,
    PAIDAMOUNT,
    CLAIMID,
    PAYORID,
    PROCEDURECODE,
    ICDCODE,
    LINEOFBUSINESS,
    MEDICAIDID,
    MEDICAREID,
    SRC_INSERTDATE,
    SRC_MODIFIEDDATE,
    DATASOURCE,
    IS_QUARANTINED,
    INSERTED_DATE,
    MODIFIED_DATE,
    IS_CURRENT)
SELECT
  SRC.TRANSACTION_KEY,
  SRC.SRC_TRANSACTIONID,
  SRC.ENCOUNTERID,
  SRC.PATIENTID,
  SRC.PROVIDERID,
  SRC.DEPTID,
  SRC.VISITDATE,
  SRC.SERVICEDATE,
  SRC.PAIDDATE,
  SRC.VISITTYPE,
  SRC.AMOUNT,
  SRC.AMOUNTTYPE,
  SRC.PAIDAMOUNT,
  SRC.CLAIMID,
  SRC.PAYORID,
  SRC.PROCEDURECODE,
  SRC.ICDCODE,
  SRC.LINEOFBUSINESS,
  SRC.MEDICAIDID,
  SRC.MEDICAREID,
  SRC.SRC_INSERTDATE,
  SRC.SRC_MODIFIEDDATE,
  SRC.DATASOURCE,
  SRC.IS_QUARANTINED,
  CURRENT_TIMESTAMP(),
  CURRENT_TIMESTAMP(),
  TRUE
FROM `dp-dwh-dev.DP_BASE_TEMP.TEMP_TRANSACTIONS` AS SRC
WHERE
  NOT EXISTS(
    SELECT 1
    FROM `dp-dwh-dev.DP_BASE_SILVER.TRANSACTIONS` AS TGT
    WHERE TGT.TRANSACTION_KEY = SRC.TRANSACTION_KEY AND TGT.IS_CURRENT = TRUE
  );

-- 4. Cleanup the temporary staging table
DROP TABLE IF EXISTS `dp-dwh-dev.DP_BASE_TEMP.TEMP_TRANSACTIONS`;

END;