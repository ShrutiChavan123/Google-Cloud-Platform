CREATE OR REPLACE PROCEDURE `dp-dwh-dev.DP_BASE_SILVER.SP_FULL_LOAD_DEPARTMENT`()
BEGIN
--full load table
TRUNCATE TABLE DP_BASE_SILVER.DEPARTMENTS;

INSERT INTO DP_BASE_SILVER.DEPARTMENTS
SELECT DISTINCT 
       CONCAT(DEPTID,'-',DATASOURCE) AS DEPARTMENT_ID,
       DEPTID AS SRC_ID,
       NAME,
       DATASOURCE,
       CASE
        WHEN DEPTID IS NULL OR NAME IS NULL THEN TRUE
        ELSE FALSE
        END AS IS_QUARANTINE
FROM
(
SELECT DISTINCT *,'hosp-a' AS DATASOURCE  FROM `DP_BASE_BRONZE.DEPARTMENTS_HA`
UNION ALL
SELECT DISTINCT *,'hosp-b' AS DATASOURCE  FROM `DP_BASE_BRONZE.DEPARTMENTS_HB`
);

END;