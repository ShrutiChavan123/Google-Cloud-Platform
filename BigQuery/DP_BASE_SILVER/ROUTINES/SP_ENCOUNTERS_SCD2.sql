CREATE OR REPLACE PROCEDURE `dp-dwh-dev.DP_BASE_SILVER.SP_ENCOUNTERS_SCD2`()
BEGIN
-- 1. Create a staging table from Bronze sources with Uppercase Columns and Quality Logic
CREATE OR REPLACE TABLE `dp-dwh-dev.DP_BASE_TEMP.TEMP_ENCOUNTERS`
AS
SELECT DISTINCT
  CONCAT(SRC_ENCOUNTERID, '-', DATASOURCE) AS ENCOUNTER_KEY,
  SRC_ENCOUNTERID,
  PATIENTID,
  PROVIDERID,
  DEPARTMENTID,
  ENCOUNTERDATE,
  ENCOUNTERTYPE,
  PROCEDURECODE,
  SRC_MODIFIEDDATE,
  DATASOURCE,
  CASE
    WHEN
      SRC_ENCOUNTERID IS NULL
      OR PATIENTID IS NULL
      OR ENCOUNTERDATE IS NULL
      OR LOWER(ENCOUNTERTYPE) = 'null'
      THEN TRUE
    ELSE FALSE
    END
    AS IS_QUARANTINED
FROM
  (
    SELECT DISTINCT
      EncounterID AS SRC_ENCOUNTERID,
      PatientID AS PATIENTID,
      ProviderID AS PROVIDERID,
      DepartmentID AS DEPARTMENTID,
      EncounterDate AS ENCOUNTERDATE,
      EncounterType AS ENCOUNTERTYPE,
      ProcedureCode AS PROCEDURECODE,
      ModifiedDate AS SRC_MODIFIEDDATE,
      'hosa' AS DATASOURCE
    FROM `dp-dwh-dev.DP_BASE_BRONZE.ENCOUNTERS_HA`
    UNION ALL
    SELECT DISTINCT
      EncounterID AS SRC_ENCOUNTERID,
      PatientID AS PATIENTID,
      ProviderID AS PROVIDERID,
      DepartmentID AS DEPARTMENTID,
      EncounterDate AS ENCOUNTERDATE,
      EncounterType AS ENCOUNTERTYPE,
      ProcedureCode AS PROCEDURECODE,
      ModifiedDate AS SRC_MODIFIEDDATE,
      'hosb' AS DATASOURCE
    FROM `dp-dwh-dev.DP_BASE_BRONZE.ENCOUNTERS_HB`
  );

-- 2. SCD Type 2 Part A: Expire (deactivate) existing records in Silver that have changed
MERGE INTO `dp-dwh-dev.DP_BASE_SILVER.ENCOUNTERS` AS TGT
USING `dp-dwh-dev.DP_BASE_TEMP.TEMP_ENCOUNTERS` AS SRC
ON
  TGT.ENCOUNTER_KEY = SRC.ENCOUNTER_KEY
  AND TGT.IS_CURRENT
    = TRUE
      WHEN
        MATCHED
        AND (
          TGT.SRC_ENCOUNTERID <> SRC.SRC_ENCOUNTERID
          OR TGT.PATIENTID <> SRC.PATIENTID
          OR TGT.PROVIDERID <> SRC.PROVIDERID
          OR TGT.DEPARTMENTID <> SRC.DEPARTMENTID
          OR TGT.ENCOUNTERDATE <> SRC.ENCOUNTERDATE
          OR TGT.ENCOUNTERTYPE <> SRC.ENCOUNTERTYPE
          OR TGT.PROCEDURECODE <> SRC.PROCEDURECODE
          OR TGT.SRC_MODIFIEDDATE <> SRC.SRC_MODIFIEDDATE
          OR TGT.DATASOURCE <> SRC.DATASOURCE
          OR TGT.IS_QUARANTINED <> SRC.IS_QUARANTINED)
        THEN UPDATE
SET TGT.IS_CURRENT = FALSE, TGT.MODIFIED_DATE = CURRENT_TIMESTAMP();

-- 3. SCD Type 2 Part B: Insert new records and the new versions of updated records
INSERT INTO `dp-dwh-dev.DP_BASE_SILVER.ENCOUNTERS`
  (
    ENCOUNTER_KEY,
    SRC_ENCOUNTERID,
    PATIENTID,
    PROVIDERID,
    DEPARTMENTID,
    ENCOUNTERDATE,
    ENCOUNTERTYPE,
    PROCEDURECODE,
    SRC_MODIFIEDDATE,
    DATASOURCE,
    IS_QUARANTINED,
    INSERTED_DATE,
    MODIFIED_DATE,
    IS_CURRENT)
SELECT
  SRC.ENCOUNTER_KEY,
  SRC.SRC_ENCOUNTERID,
  SRC.PATIENTID,
  SRC.PROVIDERID,
  SRC.DEPARTMENTID,
  SRC.ENCOUNTERDATE,
  SRC.ENCOUNTERTYPE,
  SRC.PROCEDURECODE,
  SRC.SRC_MODIFIEDDATE,
  SRC.DATASOURCE,
  SRC.IS_QUARANTINED,
  CURRENT_TIMESTAMP(),
  CURRENT_TIMESTAMP(),
  TRUE
FROM `dp-dwh-dev.DP_BASE_TEMP.TEMP_ENCOUNTERS` AS SRC
WHERE
  NOT EXISTS(
    SELECT 1
    FROM `dp-dwh-dev.DP_BASE_SILVER.ENCOUNTERS` AS TGT
    WHERE TGT.ENCOUNTER_KEY = SRC.ENCOUNTER_KEY AND TGT.IS_CURRENT = TRUE
  );

-- 4. Cleanup the temporary staging table
DROP TABLE IF EXISTS `dp-dwh-dev.DP_BASE_TEMP.TEMP_ENCOUNTERS`;

END;