CREATE OR REPLACE PROCEDURE `dp-dwh-dev.DP_BASE_SILVER.SP_CLAIMS_SCD2`()
BEGIN
-- 1. Create a staging table from Bronze source with Uppercase Columns and Quality Logic
CREATE OR REPLACE TABLE `dp-dwh-dev.DP_BASE_TEMP.TEMP_CLAIMS`
AS
SELECT
  CONCAT(SRC_CLAIMID, '-', DATASOURCE) AS CLAIM_KEY,
  SRC_CLAIMID,
  TRANSACTIONID,
  PATIENTID,
  ENCOUNTERID,
  PROVIDERID,
  DEPTID,
  SERVICEDATE,
  CLAIMDATE,
  PAYORID,
  CLAIMAMOUNT,
  PAIDAMOUNT,
  CLAIMSTATUS,
  PAYORTYPE,
  DEDUCTIBLE,
  COINSURANCE,
  COPAY,
  SRC_INSERTDATE,
  SRC_MODIFIEDDATE,
  DATASOURCE,
  CASE
    WHEN
      SRC_CLAIMID IS NULL
      OR PATIENTID IS NULL
      OR TRANSACTIONID IS NULL
      OR LOWER(CLAIMSTATUS) = 'null'
      THEN TRUE
    ELSE FALSE
    END
    AS IS_QUARANTINED
FROM
  (
    SELECT
      ClaimID AS SRC_CLAIMID,
      TransactionID AS TRANSACTIONID,
      PatientID AS PATIENTID,
      EncounterID AS ENCOUNTERID,
      ProviderID AS PROVIDERID,
      DeptID AS DEPTID,
      ServiceDate AS SERVICEDATE,
      ClaimDate AS CLAIMDATE,
      PayorID AS PAYORID,
      ClaimAmount AS CLAIMAMOUNT,
      PaidAmount AS PAIDAMOUNT,
      ClaimStatus AS CLAIMSTATUS,
      PayorType AS PAYORTYPE,
      Deductible AS DEDUCTIBLE,
      Coinsurance AS COINSURANCE,
      Copay AS COPAY,
      InsertDate AS SRC_INSERTDATE,
      ModifiedDate AS SRC_MODIFIEDDATE,
      'hosa' AS DATASOURCE
    FROM `dp-dwh-dev.DP_BASE_BRONZE.CLAIMS`
  );

-- 2. SCD Type 2 Part A: Expire (deactivate) existing records in Silver that have changed
MERGE INTO `dp-dwh-dev.DP_BASE_SILVER.CLAIMS` AS TGT
USING `dp-dwh-dev.DP_BASE_TEMP.TEMP_CLAIMS` AS SRC
ON
  TGT.CLAIM_KEY = SRC.CLAIM_KEY
  AND TGT.IS_CURRENT
    = TRUE
      WHEN
        MATCHED
        AND (
          TGT.SRC_CLAIMID <> SRC.SRC_CLAIMID
          OR TGT.TRANSACTIONID <> SRC.TRANSACTIONID
          OR TGT.PATIENTID <> SRC.PATIENTID
          OR TGT.ENCOUNTERID <> SRC.ENCOUNTERID
          OR TGT.PROVIDERID <> SRC.PROVIDERID
          OR TGT.DEPTID <> SRC.DEPTID
          OR TGT.SERVICEDATE <> SRC.SERVICEDATE
          OR TGT.CLAIMDATE <> SRC.CLAIMDATE
          OR TGT.PAYORID <> SRC.PAYORID
          OR TGT.CLAIMAMOUNT <> SRC.CLAIMAMOUNT
          OR TGT.PAIDAMOUNT <> SRC.PAIDAMOUNT
          OR TGT.CLAIMSTATUS <> SRC.CLAIMSTATUS
          OR TGT.PAYORTYPE <> SRC.PAYORTYPE
          OR TGT.DEDUCTIBLE <> SRC.DEDUCTIBLE
          OR TGT.COINSURANCE <> SRC.COINSURANCE
          OR TGT.COPAY <> SRC.COPAY
          OR TGT.SRC_MODIFIEDDATE <> SRC.SRC_MODIFIEDDATE
          OR TGT.DATASOURCE <> SRC.DATASOURCE
          OR TGT.IS_QUARANTINED <> SRC.IS_QUARANTINED)
        THEN UPDATE
SET TGT.IS_CURRENT = FALSE, TGT.MODIFIED_DATE = CURRENT_TIMESTAMP();

-- 3. SCD Type 2 Part B: Insert new records and the new versions of updated records
INSERT INTO `dp-dwh-dev.DP_BASE_SILVER.CLAIMS`
  (
    CLAIM_KEY,
    SRC_CLAIMID,
    TRANSACTIONID,
    PATIENTID,
    ENCOUNTERID,
    PROVIDERID,
    DEPTID,
    SERVICEDATE,
    CLAIMDATE,
    PAYORID,
    CLAIMAMOUNT,
    PAIDAMOUNT,
    CLAIMSTATUS,
    PAYORTYPE,
    DEDUCTIBLE,
    COINSURANCE,
    COPAY,
    SRC_INSERTDATE,
    SRC_MODIFIEDDATE,
    DATASOURCE,
    IS_QUARANTINED,
    INSERTED_DATE,
    MODIFIED_DATE,
    IS_CURRENT)
SELECT
  SRC.CLAIM_KEY,
  SRC.SRC_CLAIMID,
  SRC.TRANSACTIONID,
  SRC.PATIENTID,
  SRC.ENCOUNTERID,
  SRC.PROVIDERID,
  SRC.DEPTID,
  SRC.SERVICEDATE,
  SRC.CLAIMDATE,
  SRC.PAYORID,
  SRC.CLAIMAMOUNT,
  SRC.PAIDAMOUNT,
  SRC.CLAIMSTATUS,
  SRC.PAYORTYPE,
  SRC.DEDUCTIBLE,
  SRC.COINSURANCE,
  SRC.COPAY,
  SRC.SRC_INSERTDATE,
  SRC.SRC_MODIFIEDDATE,
  SRC.DATASOURCE,
  SRC.IS_QUARANTINED,
  CURRENT_TIMESTAMP(),
  CURRENT_TIMESTAMP(),
  TRUE
FROM `dp-dwh-dev.DP_BASE_TEMP.TEMP_CLAIMS` AS SRC
WHERE
  NOT EXISTS(
    SELECT 1
    FROM `dp-dwh-dev.DP_BASE_SILVER.CLAIMS` AS TGT
    WHERE TGT.CLAIM_KEY = SRC.CLAIM_KEY AND TGT.IS_CURRENT = TRUE
  );

-- 4. Cleanup the temporary staging table
DROP TABLE IF EXISTS `dp-dwh-dev.DP_BASE_TEMP.TEMP_CLAIMS`;

END;