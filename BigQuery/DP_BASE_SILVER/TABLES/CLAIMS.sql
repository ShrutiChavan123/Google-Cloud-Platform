CREATE TABLE IF NOT EXISTS DP_BASE_SILVER.CLAIMS
(
    CLAIM_KEY STRING OPTIONS(description = 'UNIQUE KEY FOR CLAIM RECORD'),
    SRC_CLAIMID STRING OPTIONS(description = 'SOURCE SYSTEM CLAIM IDENTIFIER'),
    TRANSACTIONID STRING OPTIONS(description = 'TRANSACTION IDENTIFIER FOR THE CLAIM'),
    PATIENTID STRING OPTIONS(description = 'UNIQUE PATIENT IDENTIFIER'),
    ENCOUNTERID STRING OPTIONS(description = 'UNIQUE ENCOUNTER IDENTIFIER'),
    PROVIDERID STRING OPTIONS(description = 'UNIQUE PROVIDER IDENTIFIER'),
    DEPTID STRING OPTIONS(description = 'DEPARTMENT IDENTIFIER'),
    SERVICEDATE STRING OPTIONS(description = 'DATE OF SERVICE PROVIDED'),
    CLAIMDATE STRING OPTIONS(description = 'DATE CLAIM WAS SUBMITTED OR CREATED'),
    PAYORID STRING OPTIONS(description = 'PAYOR IDENTIFIER'),
    CLAIMAMOUNT STRING OPTIONS(description = 'TOTAL CLAIMED AMOUNT'),
    PAIDAMOUNT STRING OPTIONS(description = 'AMOUNT PAID BY PAYOR'),
    CLAIMSTATUS STRING OPTIONS(description = 'CURRENT STATUS OF THE CLAIM'),
    PAYORTYPE STRING OPTIONS(description = 'TYPE OF PAYOR ASSOCIATED WITH THE CLAIM'),
    DEDUCTIBLE STRING OPTIONS(description = 'DEDUCTIBLE AMOUNT APPLIED TO THE CLAIM'),
    COINSURANCE STRING OPTIONS(description = 'COINSURANCE AMOUNT APPLIED TO THE CLAIM'),
    COPAY STRING OPTIONS(description = 'COPAY AMOUNT APPLIED TO THE CLAIM'),
    SRC_INSERTDATE STRING OPTIONS(description = 'SOURCE SYSTEM RECORD INSERT DATE'),
    SRC_MODIFIEDDATE STRING OPTIONS(description = 'SOURCE SYSTEM RECORD MODIFICATION DATE'),
    DATASOURCE STRING OPTIONS(description = 'SOURCE SYSTEM OF THE RECORD'),
    IS_QUARANTINED BOOLEAN OPTIONS(description = 'FLAG INDICATING WHETHER RECORD IS QUARANTINED'),
    INSERTED_DATE TIMESTAMP OPTIONS(description = 'RECORD INSERT TIMESTAMP'),
    MODIFIED_DATE TIMESTAMP OPTIONS(description = 'RECORD LAST MODIFIED TIMESTAMP'),
    IS_CURRENT BOOLEAN OPTIONS(description = 'FLAG INDICATING CURRENT ACTIVE RECORD')
)
OPTIONS (
    DESCRIPTION = 'SILVER LAYER TABLE CONTAINING CLAIM DETAILS INCLUDING PATIENT, PROVIDER, PAYOR, AMOUNTS, STATUS, AND AUDIT INFORMATION'
);