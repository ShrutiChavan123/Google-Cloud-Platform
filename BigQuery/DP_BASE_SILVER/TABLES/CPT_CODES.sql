CREATE TABLE IF NOT EXISTS DP_BASE_SILVER.CPT_CODES
(
    CP_CODE_KEY STRING OPTIONS(description = 'UNIQUE KEY FOR CPT CODE RECORD'),
    PROCEDURE_CODE_CATEGORY STRING OPTIONS(description = 'CATEGORY OF PROCEDURE CODE'),
    CPT_CODES STRING OPTIONS(description = 'CPT PROCEDURE CODE'),
    PROCEDURE_CODE_DESCRIPTIONS STRING OPTIONS(description = 'DESCRIPTION OF CPT PROCEDURE CODE'),
    CODE_STATUS STRING OPTIONS(description = 'STATUS OF THE CODE (ACTIVE/INACTIVE)'),
    DATASOURCE STRING OPTIONS(description = 'SOURCE SYSTEM OF THE RECORD'),
    IS_QUARANTINED BOOLEAN OPTIONS(description = 'FLAG INDICATING WHETHER RECORD IS QUARANTINED'),
    INSERTED_DATE TIMESTAMP OPTIONS(description = 'RECORD INSERT TIMESTAMP'),
    MODIFIED_DATE TIMESTAMP OPTIONS(description = 'RECORD LAST MODIFIED TIMESTAMP'),
    IS_CURRENT BOOLEAN OPTIONS(description = 'FLAG INDICATING CURRENT ACTIVE RECORD')
)
OPTIONS (
    DESCRIPTION = 'SILVER LAYER TABLE CONTAINING CPT PROCEDURE CODES, CATEGORIES, DESCRIPTIONS, STATUS');